-- Study programmes (BA CE, MSc ARCH…) and the courses that belong to them.
-- Applied as migration "teaching_programmes". Safe to run again.
--
-- A course lists its programmes in its metadata, key 'programmes', as programme ids
-- ("5,12"): renaming a programme renames it everywhere, and a course shared by two
-- degrees belongs to both. Only Admins change programmes or a course's programmes.
-- The ids match Stando's programmes, so the two can be linked later.

create table if not exists public.teaching_programmes (
  id integer generated by default as identity primary key,
  code text not null check (btrim(code) <> '' and length(code) <= 30),
  name text not null default '' check (length(name) <= 150),
  archived boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index if not exists teaching_programmes_code_uq on public.teaching_programmes (lower(btrim(code)));

-- Programmes are public, like the course pages that show them. Writes go through the
-- functions below, which check the caller.
alter table public.teaching_programmes enable row level security;
drop policy if exists "programmes are public" on public.teaching_programmes;
create policy "programmes are public" on public.teaching_programmes for select to anon, authenticated using (true);
revoke insert, update, delete, truncate on public.teaching_programmes from anon, authenticated;
grant select on public.teaching_programmes to anon, authenticated;

-- Every programme, A–Z by code.
create or replace function public.teaching_programmes()
 returns jsonb
 language sql
 stable security definer
 set search_path to ''
as $function$
  select coalesce(jsonb_agg(jsonb_build_object('id', p.id, 'code', p.code, 'name', p.name, 'archived', p.archived)
    order by lower(p.code)), '[]'::jsonb)
  from public.teaching_programmes p
$function$;

-- A course's programme ids, from its 'programmes' metadata ("5, 12" → {5,12}).
create or replace function teaching_private.programme_ids(p_value text)
 returns integer[]
 language sql
 immutable
 set search_path to ''
as $function$
  select coalesce(array_agg(distinct t.v::integer order by t.v::integer), '{}')
  from (select btrim(x) as v from unnest(string_to_array(coalesce(p_value, ''), ',')) as x) t
  where t.v ~ '^[0-9]{1,9}$'
$function$;

-- Writes one course's programmes, adding the metadata row when it has none and
-- removing it when the list is empty.
create or replace function teaching_private.set_course_programmes(p_sheet_name text, p_archive boolean, p_ids integer[])
 returns void
 language plpgsql
 security definer
 set search_path to ''
as $function$
declare v_value text := array_to_string(p_ids, ',');
begin
  if coalesce(v_value, '') = '' then
    delete from public.course_rows where sheet_name = p_sheet_name and is_archive = p_archive
      and type = 'metadata' and teaching_private.meta_key(b) = 'programmes';
    return;
  end if;
  update public.course_rows set c = v_value where sheet_name = p_sheet_name and is_archive = p_archive
    and type = 'metadata' and teaching_private.meta_key(b) = 'programmes';
  if not found then
    insert into public.course_rows (row_uid, sheet_name, is_archive, row_index, type, b, c)
    select 'course:' || gen_random_uuid(), p_sheet_name, p_archive,
      coalesce(max(r.row_index), 0) + 10, 'metadata', 'programmes', v_value
    from public.course_rows r where r.sheet_name = p_sheet_name and r.is_archive = p_archive and r.type = 'metadata'
    having count(*) > 0;
  end if;
end $function$;

-- Adds or edits a programme (Admins only). p_id null adds one.
create or replace function public.teaching_save_programme(p_id integer, p_code text, p_name text, p_archived boolean default false)
 returns jsonb
 language plpgsql
 security definer
 set search_path to ''
as $function$
declare v_code text := regexp_replace(btrim(coalesce(p_code, '')), '\s+', ' ', 'g');
  v_name text := regexp_replace(btrim(coalesce(p_name, '')), '\s+', ' ', 'g');
  saved public.teaching_programmes;
begin
  if coalesce(public.teaching_role(), '') not in ('global_admin', 'admin') then
    raise exception 'Only admins can change programmes' using errcode = '42501'; end if;
  if v_code = '' then raise exception 'Enter the programme code'; end if;
  if length(v_code) > 30 then raise exception 'Use at most 30 characters for the code'; end if;
  if length(v_name) > 150 then raise exception 'Use at most 150 characters for the name'; end if;
  if exists (select 1 from public.teaching_programmes p where lower(p.code) = lower(v_code) and p.id is distinct from p_id) then
    raise exception 'There is already a programme called %', v_code; end if;
  if p_id is null then
    insert into public.teaching_programmes (code, name, archived) values (v_code, v_name, coalesce(p_archived, false))
      returning * into saved;
  else
    update public.teaching_programmes p set code = v_code, name = v_name,
      archived = coalesce(p_archived, p.archived) where p.id = p_id returning * into saved;
    if not found then raise exception 'That programme no longer exists. Reload and try again.'; end if;
  end if;
  return jsonb_build_object('id', saved.id, 'code', saved.code, 'name', saved.name, 'archived', saved.archived);
end $function$;

-- Removes a programme (Admins only); its courses simply lose it.
create or replace function public.teaching_delete_programme(p_id integer)
 returns void
 language plpgsql
 security definer
 set search_path to ''
as $function$
declare course record;
begin
  if coalesce(public.teaching_role(), '') not in ('global_admin', 'admin') then
    raise exception 'Only admins can change programmes' using errcode = '42501'; end if;
  lock table public.course_rows in share row exclusive mode;
  for course in select r.sheet_name, r.is_archive, teaching_private.programme_ids(r.c) as ids from public.course_rows r
    where r.type = 'metadata' and teaching_private.meta_key(r.b) = 'programmes' loop
    if p_id = any(course.ids) then
      perform teaching_private.set_course_programmes(course.sheet_name, course.is_archive, array_remove(course.ids, p_id));
    end if;
  end loop;
  delete from public.teaching_programmes where id = p_id;
  if not found then raise exception 'That programme no longer exists.'; end if;
end $function$;

-- Sets which courses belong to a programme (Admins only): p_courses lists them all as
-- [{sheet_name, is_archive}]; every other course leaves it. Their other programmes stay.
create or replace function public.teaching_set_programme_courses(p_id integer, p_courses jsonb)
 returns void
 language plpgsql
 security definer
 set search_path to ''
as $function$
declare course record; wanted boolean;
begin
  if coalesce(public.teaching_role(), '') not in ('global_admin', 'admin') then
    raise exception 'Only admins can change programmes' using errcode = '42501'; end if;
  if not exists (select 1 from public.teaching_programmes where id = p_id) then
    raise exception 'That programme no longer exists. Reload and try again.'; end if;
  if p_courses is null or jsonb_typeof(p_courses) <> 'array' then raise exception 'Invalid course list'; end if;
  lock table public.course_rows in share row exclusive mode;
  for course in select o.sheet_name, o.is_archive,
      coalesce((select teaching_private.programme_ids(r.c) from public.course_rows r where r.sheet_name = o.sheet_name
        and r.is_archive = o.is_archive and r.type = 'metadata' and teaching_private.meta_key(r.b) = 'programmes' limit 1), '{}') as ids
    from (select distinct r.sheet_name, r.is_archive from public.course_rows r where r.type = 'metadata') o loop
    wanted := exists (select 1 from jsonb_array_elements(p_courses) e
      where e->>'sheet_name' = course.sheet_name and (e->>'is_archive')::boolean = course.is_archive);
    if wanted and not p_id = any(course.ids) then
      perform teaching_private.set_course_programmes(course.sheet_name, course.is_archive,
        (select array_agg(i order by i) from unnest(course.ids || p_id) i));
    elsif not wanted and p_id = any(course.ids) then
      perform teaching_private.set_course_programmes(course.sheet_name, course.is_archive, array_remove(course.ids, p_id));
    end if;
  end loop;
end $function$;

revoke all on function teaching_private.programme_ids(text) from public, anon, authenticated;
revoke all on function teaching_private.set_course_programmes(text, boolean, integer[]) from public, anon, authenticated;
revoke all on function public.teaching_save_programme(integer, text, text, boolean) from public, anon;
revoke all on function public.teaching_delete_programme(integer) from public, anon;
revoke all on function public.teaching_set_programme_courses(integer, jsonb) from public, anon;
grant execute on function public.teaching_save_programme(integer, text, text, boolean) to authenticated;
grant execute on function public.teaching_delete_programme(integer) to authenticated;
grant execute on function public.teaching_set_programme_courses(integer, jsonb) to authenticated;
grant execute on function public.teaching_programmes() to anon, authenticated;

-- A course's programmes are part of its Course Identity: Lecturers and Students cannot
-- change them. (As before, plus 'programmes' in the protected keys.)
create or replace function teaching_private.can_edit(p_row course_rows)
 returns boolean
 language plpgsql
 stable security definer
 set search_path to ''
as $function$
declare r text := public.teaching_role(); k text := teaching_private.meta_key(p_row.b);
begin
  if r in ('global_admin','admin') then return true; end if;
  if r is null or r not in ('lecturer','student') or not exists (
    select 1 from public.teaching_assignments a where a.email = teaching_private.email()
      and a.sheet_name = p_row.sheet_name and a.is_archive = p_row.is_archive
  ) then return false; end if;
  if p_row.type in ('module','material','funfact','project','project_file',
    'project_description','project_group','group_file','announcement') then return true; end if;
  if r = 'student' then return false; end if;
  if p_row.type = 'button' then return true; end if;
  if p_row.type <> 'metadata' then return false; end if;
  if k in ('code','title','year','semester','level','type','credits','programmes',
    'startdate','enddate','holidayweeks','holiday_startdate','holiday_start_date','holidaystartdate','holiday_start') then return false; end if;
  if k like 'professor%' then
    return exists (select 1 from teaching_private.professor_bindings b
      join public.course_rows n on n.row_uid = b.name_row_uid
      where b.email = teaching_private.email() and b.sheet_name = p_row.sheet_name
        and b.is_archive = p_row.is_archive and n.type = 'metadata' and n.b = b.professor_key
        and (p_row.b = b.professor_key or p_row.b = b.professor_key || '_link' or p_row.b = b.professor_key || '_photo'));
  end if;
  return true;
end $function$;

-- The public course list: as before, plus each course's programmes and the programme list.
create or replace function public.teaching_directory()
 returns jsonb
 language sql
 stable security definer
 set search_path to ''
as $function$
  with sites as (
    select s.id, s.email, split_part(s.email, '@', 1) as slug,
      case when s.hostname is not null and s.base_path is not null
        then 'https://' || s.hostname || s.base_path end as website,
      teaching_private.shown_name(s.email) as name,
      teaching_private.shown_photo(s.email) as photo
    from public.teaching_sites s join public.teaching_accounts a on a.email = s.email
    where a.role in ('admin', 'lecturer')
  ), offered as (
    select t.sheet_name, t.is_archive, jsonb_agg(sites.id order by sites.id) as lecturers
    from public.teaching_assignments t join sites on sites.email = t.email
    group by t.sheet_name, t.is_archive
  )
  select jsonb_build_object(
    'lecturers', coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'slug', s.slug,
        'website', s.website, 'name', s.name, 'photo', s.photo) order by s.slug)
      from sites s where exists (select 1 from offered o where o.lecturers ? s.id::text)), '[]'::jsonb),
    'courses', coalesce((select jsonb_agg(coalesce(m.meta, '{}'::jsonb) || jsonb_build_object(
        'sheet_name', o.sheet_name, 'is_archive', o.is_archive, 'lecturers', o.lecturers)
        order by o.sheet_name, o.is_archive)
      from offered o cross join lateral (
        select jsonb_object_agg(lower(btrim(r.b)), btrim(coalesce(r.c, ''))) as meta
        from public.course_rows r
        where r.sheet_name = o.sheet_name and r.is_archive = o.is_archive and r.type = 'metadata'
          and lower(btrim(r.b)) in ('code', 'title', 'semester', 'year', 'header_decoration', 'theme_colours', 'programmes')
      ) m
      where m.meta is not null), '[]'::jsonb),
    'programmes', public.teaching_programmes()
  )
$function$;

